using System.Text.RegularExpressions;
using CoinquiLindo.Application.Reports;
using Microsoft.Extensions.Options;

namespace CoinquiLindo.Infrastructure.Storage
{
    public sealed partial class FileSystemReportPhotoStorage(IOptions<ReportPhotoStorageOptions> options) : IReportPhotoStorage
    {
        private readonly string _rootPath = Path.GetFullPath(
            string.IsNullOrWhiteSpace(options.Value.RootPath)
                ? throw new InvalidOperationException($"{ReportPhotoStorageOptions.SectionName}:RootPath is not configured.")
                : options.Value.RootPath);

        public async Task SaveAsync(string photoKey, Stream content, CancellationToken cancellationToken)
        {
            var path = GetPath(photoKey);
            Directory.CreateDirectory(_rootPath);
            var tempPath = Path.Combine(_rootPath, $"{photoKey}.{Guid.NewGuid():N}.tmp");

            try
            {
                await using (var file = new FileStream(tempPath, FileMode.CreateNew, FileAccess.Write, FileShare.None,
                    bufferSize: 81920, FileOptions.Asynchronous))
                {
                    await content.CopyToAsync(file, cancellationToken);
                }

                // Atomic publish: readers never see a partially written photo
                File.Move(tempPath, path, overwrite: false);
            }
            finally
            {
                File.Delete(tempPath);
            }
        }

        public Task<Stream?> OpenReadAsync(string photoKey, CancellationToken cancellationToken)
        {
            var path = GetPath(photoKey);

            try
            {
                Stream stream = new FileStream(path, FileMode.Open, FileAccess.Read, FileShare.Read,
                    bufferSize: 81920, FileOptions.Asynchronous | FileOptions.SequentialScan);
                return Task.FromResult<Stream?>(stream);
            }
            catch (Exception ex) when (ex is FileNotFoundException or DirectoryNotFoundException)
            {
                return Task.FromResult<Stream?>(null);
            }
        }

        public Task DeleteAsync(string photoKey, CancellationToken cancellationToken)
        {
            File.Delete(GetPath(photoKey));
            return Task.CompletedTask;
        }

        // Keys are generated by the domain; anything else could be a path traversal attempt
        private string GetPath(string photoKey) =>
            PhotoKeyPattern().IsMatch(photoKey)
                ? Path.Combine(_rootPath, photoKey)
                : throw new ArgumentException("Invalid report photo key.", nameof(photoKey));

        [GeneratedRegex("^[0-9a-f]{32}\\.(jpg|png)$", RegexOptions.CultureInvariant)]
        private static partial Regex PhotoKeyPattern();
    }
}
