using CoinquiLindo.Domain.Entities;

namespace CoinquiLindo.Domain.RepositoriesInterfaces
{
    public interface IShiftRepository
    {
        Task AddAsync(Shift shift, CancellationToken cancellationToken = default);
        Task<IReadOnlyList<Shift>> GetByHouseIdAsync(Guid houseId, CancellationToken cancellationToken = default);
        Task<Shift?> GetByIdAsync(Guid houseId, Guid shiftId, CancellationToken cancellationToken = default);
        Task UpdateAsync(Shift shift, CancellationToken cancellationToken = default);
        // Cross-house read used by the due-soon reminder job: DueDate in (fromExclusive, toInclusive]
        Task<IReadOnlyList<Shift>> GetDueBetweenAsync(DateTime fromExclusive, DateTime toInclusive, CancellationToken cancellationToken = default);
        // Shifts generated by a rotation plan that end on or after the given day (tracked: they may be removed)
        Task<IReadOnlyList<Shift>> GetByRotationPlanAsync(Guid rotationPlanId, DateOnly endingFrom, CancellationToken cancellationToken = default);
        Task RemoveRangeAsync(IReadOnlyCollection<Shift> shifts, CancellationToken cancellationToken = default);
        // False when another request or job already generated the same rotation shifts (unique index): nothing is saved
        Task<bool> TryAddRangeAsync(IReadOnlyCollection<Shift> shifts, CancellationToken cancellationToken = default);
    }
}
