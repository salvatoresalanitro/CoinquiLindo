using CoinquiLindo.Domain.Enums;
using CoinquiLindo.Domain.Exceptions;

namespace CoinquiLindo.Domain.Entities
{
    public class Shift
    {
        public Guid Id { get; private set; }
        public Guid HouseId { get; private set; }
        public Tenant AssignedTenant { get; private set; }
        public Room AssignedRoom { get; private set; }
        // Calendar days in the house time zone, both inclusive
        public DateOnly StartDate { get; private set; }
        public DateOnly EndDate { get; private set; }

        // UTC instant at which EndDate ends in the house time zone: the deadline used by reminders and history
        public DateTime DueDate { get; private set; }

        // Set when the shift was generated by the rotation plan of the house; plain reference, the plan can be removed
        public Guid? RotationPlanId { get; private set; }
        public bool IsFromRotation => RotationPlanId is not null;

        // Optional: a tenant resting that week, chosen by the assignee to help with this shift
        public Tenant? HelperTenant { get; private set; }

        private readonly List<ShiftChecklistItem> _checklist = new();
        private readonly List<Report> _reports = new();

        public IReadOnlyCollection<Report> Reports => _reports.AsReadOnly();
        public IReadOnlyCollection<ShiftChecklistItem> Checklist => _checklist.AsReadOnly();

        public Shift(Guid houseId, Tenant assignedTenant, Room assignedRoom, DateOnly startDate, DateOnly endDate, TimeZoneInfo timeZone,
            Guid? rotationPlanId = null)
        {
            if (houseId == Guid.Empty)
            {
                throw new DomainValidationException("Shift.HouseRequired", "A shift must belong to a house.");
            }

            ArgumentNullException.ThrowIfNull(assignedTenant, nameof(assignedTenant));
            ArgumentNullException.ThrowIfNull(assignedRoom, nameof(assignedRoom));

            ArgumentNullException.ThrowIfNull(timeZone, nameof(timeZone));

            if (endDate < startDate)
            {
                throw new DomainValidationException("Shift.InvalidDateRange", "End date cannot be before start date.");
            }

            Id = Guid.NewGuid();
            HouseId = houseId;
            AssignedTenant = assignedTenant;
            AssignedRoom = assignedRoom;
            StartDate = startDate;
            EndDate = endDate;
            DueDate = EndOfDayUtc(endDate, timeZone);
            RotationPlanId = rotationPlanId;

            // Initialize the checklist with the cleaning tasks of the assigned room
            foreach (var task in assignedRoom.CleaningTasks)
            {
                _checklist.Add(new ShiftChecklistItem(task.Description));
            }
        }

        public void MarkItemAsCompleted(Guid checklistId)
        {
            var item = _checklist.FirstOrDefault(i => i.Id == checklistId);
            if (item == null)
            {
                throw new NotFoundException(nameof(ShiftChecklistItem), checklistId);
            }

            item.MarkAsCompleted();
        }

        public void AddReport(Report report)
        {
            ArgumentNullException.ThrowIfNull(report, nameof(report));

            if(report.Reporter.Id == AssignedTenant.Id)
            {
                throw new SelfReportNotAllowedException();
            }

            _reports.Add(report);
        }

        public bool CanReport(Guid tenantId) => tenantId != AssignedTenant.Id;

        public bool CanChooseHelper(Guid tenantId) => IsFromRotation && tenantId == AssignedTenant.Id;

        // Whether the helper is actually resting that week depends on the other shifts: checked by the caller
        public void SetHelper(Guid requesterTenantId, Tenant helper)
        {
            ArgumentNullException.ThrowIfNull(helper, nameof(helper));

            if (!CanChooseHelper(requesterTenantId) || helper.Id == AssignedTenant.Id)
            {
                throw new ShiftHelperNotAllowedException();
            }

            HelperTenant = helper;
        }

        // The assignee can change their mind and the helper can step back
        public void RemoveHelper(Guid requesterTenantId)
        {
            if (requesterTenantId != AssignedTenant.Id && requesterTenantId != HelperTenant?.Id)
            {
                throw new ShiftHelperNotAllowedException();
            }

            HelperTenant = null;
        }

        // The reporter already backs the report and the assignee has a conflict of interest
        public bool CanVoteOnReport(Report report, Guid tenantId) =>
            tenantId != report.Reporter.Id && tenantId != AssignedTenant.Id;

        public void VoteReport(Guid reportId, Tenant voter, VoteType type)
        {
            ArgumentNullException.ThrowIfNull(voter, nameof(voter));

            if (!Enum.IsDefined(type))
            {
                throw new DomainValidationException("ReportVote.InvalidType", "A vote must be Up or Down.");
            }

            var report = GetReport(reportId);
            if (!CanVoteOnReport(report, voter.Id))
            {
                throw new ReportVoteNotAllowedException();
            }

            report.SetVote(voter.Id, type);
        }

        public void RemoveReportVote(Guid reportId, Guid voterTenantId) =>
            GetReport(reportId).RemoveVote(voterTenantId);

        public Report GetReport(Guid reportId) =>
            _reports.FirstOrDefault(report => report.Id == reportId)
                ?? throw new NotFoundException(nameof(Report), reportId);

        public bool IsShiftFullyCompleted => _checklist.All(c => c.IsCompleted);

        // A day ends when the local clock first reaches midnight of the next day
        private static DateTime EndOfDayUtc(DateOnly day, TimeZoneInfo timeZone)
        {
            var nextMidnight = day.AddDays(1).ToDateTime(TimeOnly.MinValue, DateTimeKind.Unspecified);

            TimeSpan offset;
            if (timeZone.IsInvalidTime(nextMidnight))
            {
                // Clocks jump forward exactly at midnight: the day ends at the jump, still on the previous offset
                offset = timeZone.GetUtcOffset(nextMidnight.AddHours(-3));
            }
            else if (timeZone.IsAmbiguousTime(nextMidnight))
            {
                // Midnight happens twice (clocks go back to it): the first one, on the larger offset, ends the day
                offset = timeZone.GetAmbiguousTimeOffsets(nextMidnight).Max();
            }
            else
            {
                offset = timeZone.GetUtcOffset(nextMidnight);
            }

            return DateTime.SpecifyKind(nextMidnight - offset, DateTimeKind.Utc);
        }

#pragma warning disable CS8618 // It's needed for EF Core to work properly, but we don't want to allow it to be used outside of EF Core.
        private Shift() { }
#pragma warning restore CS8618
    }
}
